  partials.sort((a, b) => b[0].length - a[0].length);

  function containsChinese(text) {
    return /[一-鿿㐀-䶿]/.test(text);
  }

  function translateText(text) {
    if (!text || lang !== "en") return text;
    const trimmed = text.trim();
    if (!containsChinese(trimmed)) return text;
    if (dict[trimmed]) return text.replace(trimmed, dict[trimmed]);
    let result = text;
    for (const [zh, en] of partials) {
      if (result.includes(zh)) result = result.replaceAll(zh, en);
    }
    return result;
  }

  function translateNode(node) {
    if (lang !== "en") return;
    if (node.nodeType === Node.TEXT_NODE) {
      const original = node.textContent;
      if (!containsChinese(original)) return;
      const translated = translateText(original);
      if (translated !== original) node.textContent = translated;
    } else if (node.nodeType === Node.ELEMENT_NODE) {
      const tag = node.tagName;
      if (tag === "SCRIPT" || tag === "STYLE" || tag === "SVG") return;
      for (const attr of ["placeholder", "aria-label", "title"]) {
        const val = node.getAttribute(attr);
        if (val && containsChinese(val)) {
          const translated = translateText(val);
          if (translated !== val) node.setAttribute(attr, translated);
        }
      }
      if (tag === "OPTION" || tag === "BUTTON" || tag === "LABEL" || tag === "A" || tag === "LEGEND" || tag === "SUMMARY") {
        for (const child of node.childNodes) translateNode(child);
        return;
      }
      for (const child of node.childNodes) translateNode(child);
    }
  }

  function translateTree(root) {
    if (lang !== "en" || !root) return;
    translateNode(root);
  }

  let translating = false;
  function init() {
    if (lang === "en") {
      document.documentElement.lang = "en";
      const title = document.title;
      if (containsChinese(title)) document.title = translateText(title) || "Rewear Studio";
      translateTree(document.body);
    }
    const observer = new MutationObserver(mutations => {
      if (lang !== "en" || translating) return;
      translating = true;
      try {
        for (const mutation of mutations) {
          for (const node of mutation.addedNodes) translateNode(node);
        }
      } finally { translating = false; }
    });
    observer.observe(document.body, { childList: true, subtree: true });
  }

  function setLang(newLang) {
    lang = newLang;
    try { localStorage.setItem("rewear-lang", lang); } catch (_) {}
    location.reload();
  }

  function toggleLang() {
    setLang(lang === "en" ? "zh-TW" : "en");
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }

  return { t, get lang() { return lang; }, setLang, toggleLang, translateTree, translateText };
